#!/usr/bin/env python3
"""Generate `tests/vectors.json` from the firmware's own modules.

There are now three implementations of this pairing crypto sharing no code —
the Python firmware, the TypeScript in `../src/`, and the Kotlin in
`../../android_demo/`. A disagreement between any two of them is a pairing that
simply never works, with no error at either end and nothing in any log. These
vectors are the only thing that catches that.

The generator imports the *firmware*, not a copy of it. If somebody changes the
HKDF salt, the info labels, the claim alphabet or the AAD string, this file
regenerates into something different and the TypeScript tests fail — which is
the entire point. Do not hand-edit `vectors.json`.

    make -C .. vectors        # regenerate
    make -C .. test           # check the TypeScript against it

The sealed envelope below is the direction that matters most: Python seals, the
browser opens. The other direction is covered by `check_envelope.py`, which
takes a TypeScript-sealed envelope on stdin and opens it here.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIRMWARE = HERE.parent.parent / "rpi_firmware"
sys.path.insert(0, str(FIRMWARE))

from snapcare_dispenser import envelope, provisioning, sc1  # noqa: E402

#: Fixed so the file regenerates byte-identically. AES-GCM is only safe with a
#: unique IV per message under one key; this is a test fixture with one message,
#: and pinning it is what makes the vector reproducible. Never do this in
#: anything that seals more than once — `seal()` uses os.urandom, correctly.
FIXED_IV = bytes(range(12))

#: Not a real device's code. Ten characters of the printed alphabet.
SAMPLE_CLAIM = "6V9F59QK67"


def sealed_with_fixed_iv(key: bytes, device_id: str, slot: str, rev: int, payload: dict) -> dict:
    """`envelope.seal` with the randomness removed, so the vector is stable."""
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    ciphertext = AESGCM(key).encrypt(
        FIXED_IV,
        json.dumps(payload, separators=(",", ":")).encode(),
        envelope.aad(device_id, slot, rev),
    )
    return {
        "v": envelope.VERSION,
        "rev": rev,
        "alg": envelope.ALG,
        "iv": envelope._b64(FIXED_IV),
        "ct": envelope._b64(ciphertext),
    }


def build() -> dict:
    claim = SAMPLE_CLAIM
    device_id = provisioning.device_id(claim)
    box = provisioning.box_key(claim)

    schedule = {"payload": "SC1*W*1:0800.2000-127-030/3:1900-021-000"}
    report = {
        "at": "2026-08-01T09:15:00",
        "firmware": "test",
        "desiredRev": 7,
        "lastError": "",
        "network": {"ssid": "Home", "address": "192.168.1.42",
                    "deviceUrl": "http://pilldispenser.local/"},
        "events": [{"at": "2026-08-01T08:00:04", "tray": 1, "time": "0800",
                    "taken": True, "confirmed": True, "reason": "released",
                    "seq": 7, "sc1": "SC1*E*1*0800*T*07"}],
    }

    return {
        "_comment": (
            "Generated by tools/make_vectors.py from the firmware. Do not edit by hand — "
            "run `make vectors`."
        ),

        # ── the claim code ────────────────────────────────────────────────
        "claim": {
            "sample": claim,
            "formatted": provisioning.format_claim(claim),
            "normalise": [
                {"input": "6v9f5-9qk67", "expect": claim},
                {"input": "  6V9F5 9QK67  ", "expect": claim},
                {"input": "6V9F5-9QK6", "expect": "", "why": "nine characters — never padded"},
                {"input": "6V9F5-9QK678", "expect": "", "why": "eleven — never truncated"},
                {"input": "OIL01ABCDE", "expect": "",
                 "why": "O, I, L, 0 and 1 are not in the alphabet, so this is five characters"},
            ],
        },

        # ── the three keys ────────────────────────────────────────────────
        "keys": {
            "claim": claim,
            "hkdfSalt": provisioning._HKDF_SALT.decode(),
            "deviceId": device_id,
            "accessToken": provisioning.access_token(claim),
            "boxKeyHex": box.hex(),
        },

        # ── HKDF itself, against RFC 5869 test case 1 ─────────────────────
        "hkdfRfc5869": {
            "ikmHex": "0b" * 22,
            "saltHex": "000102030405060708090a0b0c",
            "infoHex": "f0f1f2f3f4f5f6f7f8f9",
            "length": 42,
            "okmHex": provisioning.hkdf_sha256(
                bytes.fromhex("0b" * 22),
                bytes.fromhex("000102030405060708090a0b0c"),
                bytes.fromhex("f0f1f2f3f4f5f6f7f8f9"),
                42,
            ).hex(),
        },

        # ── the sealed envelope ───────────────────────────────────────────
        "envelope": {
            "deviceId": device_id,
            "aadExample": envelope.aad(device_id, "desired", 7).decode(),
            "desired": {
                "rev": 7,
                "plaintext": schedule,
                "sealed": sealed_with_fixed_iv(box, device_id, "desired", 7, schedule),
            },
            "reported": {
                "rev": 3,
                "plaintext": report,
                "sealed": sealed_with_fixed_iv(box, device_id, "reported", 3, report),
            },
            "mustNotOpen": [
                {"why": "sealed for 'desired', presented as 'reported'",
                 "slot": "reported",
                 "sealed": sealed_with_fixed_iv(box, device_id, "desired", 7, schedule)},
                {"why": "the revision was edited after sealing",
                 "slot": "desired",
                 "sealed": {**sealed_with_fixed_iv(box, device_id, "desired", 7, schedule),
                            "rev": 8}},
            ],
        },

        # ── SC1*W*, the lossless schedule form ────────────────────────────
        "weekly": [
            {
                "slots": [{"tray": 1, "times": ["0800", "2000"], "days": 127, "durationDays": 30},
                          {"tray": 3, "times": ["1900"], "days": 21, "durationDays": 0}],
                "payload": sc1.encode_weekly([
                    sc1.SlotSchedule(slot=1, times=[480, 1200], days=127, duration_days=30),
                    sc1.SlotSchedule(slot=3, times=[1140], days=21, duration_days=0),
                ]),
            },
            {
                "slots": [{"tray": 2, "times": ["0730"], "days": 127, "durationDays": 0}],
                "payload": sc1.encode_weekly([
                    sc1.SlotSchedule(slot=2, times=[450], days=127, duration_days=0),
                ]),
            },
        ],
    }


def main() -> int:
    if not envelope.available():
        print(envelope.UNAVAILABLE_HINT, file=sys.stderr)
        return 1

    out = HERE.parent / "tests" / "vectors.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(build(), indent=2, sort_keys=False) + "\n"

    if "--check" in sys.argv:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print(f"{out} is stale — run `make vectors`", file=sys.stderr)
            return 1
        print(f"{out.name} is current")
        return 0

    out.write_text(text, encoding="utf-8")
    print(f"wrote {out.relative_to(Path.cwd()) if str(out).startswith(os.getcwd()) else out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
