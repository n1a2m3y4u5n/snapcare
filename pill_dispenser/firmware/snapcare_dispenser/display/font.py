WIDTH = 5
HEIGHT = 7
#: One blank column between characters, so a scale-3 string has a 3 px gap.
ADVANCE = WIDTH + 1


def text_width(text: str, scale: int = 1) -> int:
    """How wide `text` will be. Includes the gaps, not the trailing one."""
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def draw(canvas, x: int, y: int, text: str, value: int, scale: int = 1) -> int:
    """Draw `text`, returning the x it ended at.

    Unknown characters become `?` rather than a gap or an exception. A screen
    that silently loses a character from an SSID is a person typing the wrong
    network name; a screen that raises is a dispenser that stopped dispensing
    because somebody named their WiFi with an emoji.
    """
    cursor = x
    for character in text.upper():
        glyph = GLYPHS.get(character) or GLYPHS["?"]
        canvas.blit(cursor, y, glyph, WIDTH, value, scale)
        cursor += ADVANCE * scale
    return cursor - scale


def draw_centred(canvas, y: int, text: str, value: int, scale: int = 1) -> None:
    draw(canvas, canvas.centre(text_width(text, scale)), y, text, value, scale)
