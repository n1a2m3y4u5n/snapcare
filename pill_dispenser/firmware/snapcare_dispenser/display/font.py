"""A 5x7 bitmap font, and the deliberately small set of characters in it.

This project's founding constraint is that the person in front of the machine
cannot be assumed to read. So text is not the channel — a colour and a glyph
are — and this font exists for the three things that are not text:

    a tray number      1 .. 8
    a time             08:00
    a network name     SNAPCARE-V5XH, on the setup screen only

Everything else on a dose screen is a picture. That is why there is no lower
case here and no punctuation beyond what a clock and an SSID need: a font with
more in it is an invitation to write a sentence on a screen the one person this
is built for cannot read.

Each glyph is five columns wide and seven rows tall, stored as seven bytes with
bit 4 leftmost. Scaled by whole numbers only — see `Canvas.blit`.
"""
from __future__ import annotations

