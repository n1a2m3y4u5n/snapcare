/**
 * 카메라를 가운데 두고 나머지를 그 둘레에 놓는다.
 *
 * 왜 바꾸는가
 * -----------
 * 홈이 세로로 긴 목록이었다. 위에서부터 제목, 알림 카드들, 카메라 버튼, 표본,
 * 추론 카드, 오늘 누적, 일지 질문, 최근 목록. 카메라가 가운데 끼어 있고 그
 * 아래로 통계가 계속 이어져서, **가장 중요한 것 하나가 여덟 개 중 하나**로 보였다.
 *
 * 이 앱에서 사람이 하는 일은 하나다 — 사진을 찍는 것. 나머지는 그 결과를 되짚는
 * 것이고, 되짚는 것에는 급할 것이 없다. 그래서 카메라를 화면 가운데에 크게 두고,
 * 나머지는 그 둘레에 위성처럼 돌린다. 통계는 자기 화면으로 옮긴다(둘 다 이미 있다 —
 * `/nutrition` 과 `/history`).
 *
 * 왜 각도를 계산해서 쓰는가
 * -------------------------
 * 손으로 좌표를 박으면 위성 수가 바뀔 때마다 다시 박아야 하고, 그때 한 개가 다른
 * 것 위에 겹쳐도 코드만 봐서는 안 보인다. 각도에서 뽑으면 몇 개를 놓든 고르게
 * 벌어진다.
 *
 * 백분율로 낸다. 화면 폭이 320px 인 폰과 440px 인 폰에서 같은 그림이 나와야 하고,
 * 픽셀로 박으면 좁은 화면에서 위성이 상자 밖으로 나간다.
 */

export interface OrbitSpot {
  /** 컨테이너 폭 대비 가로 위치(%) — 위성의 **중심** */
  left: number;
  /** 컨테이너 높이 대비 세로 위치(%) */
  top: number;
}

/**
 * 위성 자리 — 12시에서 시작해 원을 고르게 나눈다.
 *
 * 처음에는 6시 방향을 비웠다. 가운데 버튼 밑에 "Scan something" 이라는 이름을
 * 절대 위치로 얹어 두었기 때문인데, 실제로 그려 보니 **글자가 아래 위성 둘에
 * 깔렸다.** 위성을 피해 각도를 좁히는 것으로는 안 된다 — 위성은 지름 20% 짜리
 * 원이고 글자는 폭이 그 세 배라, 원 안에 남는 자리가 없다.
 *
 * 그래서 글자를 원 밖으로 내보냈다(`Orbit.tsx` 가 컨테이너 아래 흐름에 둔다).
 * 그러면 원 전체를 쓸 수 있고, 이 함수는 가장 단순한 배치 — 고르게 나누기 — 로
 * 돌아온다. 겹칠 자리가 아예 없어지는 쪽이 각도를 피해 다니는 것보다 낫다.
 *
 * 시험도 함께 고쳤다. "6시를 비웠는가" 는 위성끼리만 보고 글자는 안 봐서, 실제로
 * 깔리는 배치를 통과시키고 있었다.
 *
 * 반지름은 왜 0.78 인가
 * ---------------------
 * 0.8 이었고, 그것은 위성의 바깥 모서리가 컨테이너 모서리에 **정확히 닿는** 값이다 —
 * 여백이 0 이다. 산수로는 안 넘치지만 그림자와 배지는 상자 밖으로 나가고, 실제
 * 화면에서 위성 끝이 잘려 보였다. 딱 맞는 것과 들어가는 것은 다르다.
 *
 * 0.78 이면 바깥에 2% 가 남는다(340px 상자에서 7px). 그리고 위성이 안쪽으로 당겨지면서
 * 가운데 버튼과의 사이도 좁아진다 — 그 사이가 넓으면 여섯 개가 한 덩어리로 안 읽히고
 * 가운데가 "따로 떨어진 것" 이 된다. 이 화면은 하나를 누르라는 화면이다.
 *
 * @param count  위성 수
 * @param radius 컨테이너 반지름 대비 궤도 반지름(0–1).
 */
export function orbitSpots(count: number, radius = 0.78): OrbitSpot[] {
  if (count <= 0) return [];

  const step = 360 / count;
  return Array.from({ length: count }, (_, i) => {
    const deg = -90 + step * i;      // 화면 좌표에서 -90도가 12시다
    const rad = (deg * Math.PI) / 180;
    return {
      left: 50 + Math.cos(rad) * radius * 50,
      top: 50 + Math.sin(rad) * radius * 50,
    };
  });
}

/** 두 자리가 서로 닿는가. 겹침 검사용 — 위성 지름도 %로 준다. */
export function overlaps(a: OrbitSpot, b: OrbitSpot, diameterPct: number): boolean {
  const dx = a.left - b.left;
  const dy = a.top - b.top;
  return Math.hypot(dx, dy) < diameterPct;
}
