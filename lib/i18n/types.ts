/**
 * 한 언어가 말하는 방식.
 *
 * 낱말만 바꿔서는 문장이 되지 않는다. 영어는 "캡슐을, 식사와 함께, 하루 세 번" 순으로
 * 놓지만 한국어·우르두어·벵골어는 꾸밈말이 앞에 온다. 그대로 이으면 그 언어의 문장이
 * 아니라 영어 문장에 남의 낱말을 끼운 것이 된다.
 *
 * 그래서 어순을 한 칸 둔다. 언어학적으로는 거친 구분이다 — 실제 어순은 이보다 훨씬
 * 많은 것에 달려 있다. 다만 우리가 만드는 문장은 [빈도] + [머리] + [꾸밈] 세 조각이
 * 전부라, 이 한 칸으로 여섯 언어가 모두 자연스러운 자리에 놓인다. 조각이 늘어나면
 * 이 구분도 늘려야 한다.
 */
export interface SayPack {
  /**
   * 꾸밈말을 머리 앞에 놓는가 뒤에 놓는가.
   *
   *   head-first  영어·인도네시아어·하우사어·루마니아어 — "A capsule, with food"
   *   mod-first   한국어·우르두어·벵골어 — "식사와 함께 캡슐을 드세요"
   */
  order: 'head-first' | 'mod-first';
  /** 조각 사이에 넣는 것. 영어는 ", ", 한국어는 " ". */
  join: string;
  /** `개념.칸` → 그 언어의 말. 빠진 열쇠는 영어로 떨어진다. */
  phrases: Record<string, string>;
}
