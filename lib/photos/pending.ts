'use client';

/**
 * 홈에서 찍은 사진을 판독 화면으로 넘기는 자리.
 *
 * 왜 필요한가
 * -----------
 * 홈의 큰 단추를 누르면 **그 자리에서** 기기 카메라가 열려야 한다. 화면을 먼저
 * 넘기고 거기서 열 수는 없다 — 브라우저는 파일 고르기를 **사람이 방금 누른 것**에만
 * 허락한다(user activation). 화면이 바뀌는 사이에 그 허락이 끊기고, 아무 일도 안
 * 일어나는 단추가 된다.
 *
 * 그래서 파일 입력이 홈에 있고, 판독은 `/camera` 가 한다. 그 둘 사이로 사진 한 장을
 * 건네는 것이 이 파일의 전부다.
 *
 * 왜 저장소가 아닌가
 * ------------------
 * `File` 은 `localStorage` 에 못 넣고, 넣을 이유도 없다 — 다음 화면이 읽는 즉시
 * 쓸모가 끝난다. 모듈 안의 변수 하나면 되고, 새로고침하면 사라지는 것이 맞다
 * (새로고침한 사람은 그 사진을 기다리고 있지 않다).
 *
 * **읽으면 비운다.** 안 비우면 판독 화면에 다시 들어올 때마다 같은 사진이 또 돌고,
 * 사람은 자기가 찍지 않은 것의 판정을 본다.
 */

let pending: File | null = null;

/** 홈에서 방금 찍은 사진을 맡긴다. */
export function setPendingShot(file: File): void {
  pending = file;
}

/** 맡긴 사진을 가져간다. 한 번만 나온다. */
export function takePendingShot(): File | null {
  const file = pending;
  pending = null;
  return file;
}
