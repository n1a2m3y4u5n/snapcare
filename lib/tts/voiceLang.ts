/**
 * 이 문장을 어느 언어의 목소리로 읽을 것인가.
 *
 * 무엇이 문제인가
 * ---------------
 * 사용자가 말하는 언어를 한국어로 고르면 앱은 한국어 목소리로 읽는다. 그런데 이
 * 앱의 문장이 전부 번역돼 있지는 않다 — 사전(lib/i18n/say)에 있는 것만 한국어로
 * 나오고, 나머지는 영어 원문 그대로 나간다. 제품명, 아직 안 옮긴 화면 문구, 처방전
 * 에서 읽어온 복용 문장 같은 것들이다.
 *
 * 그 영어 문장을 한국어 목소리가 읽으면 **한국 사람이 영어를 소리 나는 대로 읽는
 * 소리**가 난다. 알아들을 수 없고, 무엇보다 이 앱에서 소리는 장식이 아니라 글을 못
 * 읽는 사람에게 도착하는 유일한 통로다.
 *
 * 어떻게 가르나
 * -------------
 * 문자 체계로만 판단한다. 한국어·벵골어·우르두어는 라틴 문자를 안 쓰므로, 그 언어로
 * 읽으라고 했는데 문장에 그 글자가 하나도 없으면 **번역이 안 된 문장**이다. 그러면
 * 영어 목소리로 읽는다.
 *
 * 이 규칙이 못 가르는 것도 적어 둔다. 하우사·인도네시아어·루마니아어는 라틴 문자라
 * 영어 문장과 글자만으로는 구별되지 않는다. 그쪽은 그대로 둔다 — 루마니아어 목소리가
 * 영어를 읽는 것은 한국어 목소리가 읽는 것보다 훨씬 가깝고, 더 잘 가르려면 사전을
 * 통째로 뒤져야 하는데 그 값이 이득보다 크다.
 */

/** 라틴 문자를 안 쓰는 언어와 그 글자 범위. */
const SCRIPTS: Record<string, RegExp> = {
  ko: /[가-힣ᄀ-ᇿ㄰-㆏]/,
  bn: /[ঀ-৿]/,
  ur: /[؀-ۿݐ-ݿ]/,
  ar: /[؀-ۿݐ-ݿ]/,
  hi: /[ऀ-ॿ]/,
  th: /[฀-๿]/,
  zh: /[一-鿿]/,
  ja: /[぀-ヿ一-鿿]/,
};

/** 읽을 만한 라틴 글자가 있는가. 숫자와 기호만 있으면 어느 목소리든 상관없다. */
const HAS_LATIN = /[A-Za-z]/;

/**
 * 실제로 쓸 목소리의 언어 태그.
 *
 * @param text 읽을 문장
 * @param want 사용자가 고른 언어 (`'ko'`, `'ko-KR'`, `'en'` …)
 */
export function voiceLangFor(text: string, want: string): string {
  const base = want.split('-')[0].toLowerCase();
  const script = SCRIPTS[base];
  if (!script) return want;               // 라틴 문자를 쓰는 언어면 그대로
  if (script.test(text)) return want;     // 그 언어 글자가 있으면 제 목소리로
  if (!HAS_LATIN.test(text)) return want; // 숫자·기호뿐이면 굳이 바꾸지 않는다
  /*
    여기까지 왔다는 것은 "한국어로 읽어라" 인데 문장에 한글이 한 자도 없고 영문이
    있다는 뜻이다. 번역이 안 된 문장이므로 영어 목소리로 읽는다.

    en-US 로 못박는다. 브라우저 기본값에 맡기면 다시 기기 기본 음성으로 떨어지고,
    한국어 환경의 기본값이 바로 한국어 음성이라 고치려던 것으로 되돌아간다.
  */
  return 'en-US';
}
