'use client';

import { useEffect } from 'react';

import { useProfile } from '@/stores/profile';
import type { SurveyRow } from './infer.ts';

/**
 * 일지가 알아낸 것을 **스스로 목록에 넣는다.**
 *
 * 왜 묻지 않는가
 * --------------
 * 물어보고 있었다. 화면에 "Add to my list" 버튼이 뜨고, 누르면 그 조건이 프로필에
 * 들어가고, 그때부터 판정 엔진이 모든 음식을 그것으로 검사한다.
 *
 * 그 버튼을 누를 수 있는 사람은 그 버튼을 읽을 수 있는 사람이다. **이 앱은 글을 못
 * 읽는 사람을 위해 만들어졌고**, 그 사람에게는 화면 아래쪽의 주황색 네모가 "여기를
 * 누르면 앞으로 이 성분이 든 음식에 빨간불이 켜집니다" 라는 뜻이 아니다. 누르지
 * 않으면 아무 일도 안 일어나고, 안 일어난다는 사실조차 안 보인다.
 *
 * 그래서 앱이 넣는다. 근거가 섰으면 — 통계 검정을 통과했으면 — 다음 끼니부터 경고가
 * 뜬다.
 *
 * 이것이 진단이 되지 않게 하는 것들
 * ---------------------------------
 * 이 저장소는 "이 앱은 진단하지 않는다" 를 여러 곳에 적어 두었고, 스스로 목록에
 * 넣는 것은 그 선에 가까이 간다. 세 가지가 그것을 선 안쪽에 붙들어 둔다.
 *
 *  · **근거가 화면에 있다.** 몇 번 먹고 몇 번 불편했는지가 카드에 숫자로 있다.
 *    앱이 무엇을 보고 그랬는지 사람이 확인할 수 있다.
 *  · **뗄 수 있다.** 뗀 것은 다시 안 붙는다(`refused`). 끌 수 없는 경고는 사람이
 *    앱을 끄게 만든다.
 *  · **자기 기록이다.** 이것은 검사 결과가 아니라 그 사람이 답한 끼니들이고,
 *    화면이 그렇게 말한다.
 *
 * 언제 넣는가
 * -----------
 * `significant` 일 때만이다. 그 값은 피셔 정확검정을 통과했다는 뜻이고, 통과하려면
 * 그 성분을 먹고 불편했던 것이 세 번, 먹은 것이 네 번, 안 먹은 끼니가 세 번은 있어야
 * 한다(`infer.ts`). 그보다 적으면 검정 자체를 안 돌린다.
 */
export function useLearnedConditions(rows: SurveyRow[]): void {
  const learn = useProfile((s) => s.learnCondition);

  useEffect(() => {
    for (const row of rows) {
      if (row.significant) learn(row.condition.id);
    }
    // `learn` 은 스토어에서 오는 안정된 함수다. `rows` 가 바뀔 때만 돈다.
  }, [rows, learn]);
}
